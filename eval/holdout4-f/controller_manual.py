class Builder:
    def __init__(self):
        self.doc = Document()
        a4(self.doc, top=2.2, bottom=2.4, left=2.4, right=2.4)
        st = self.doc.styles
        style_fonts(st['Normal'], LATIN, ZH, size=11, lang_ea='zh-CN')
        st['Normal'].paragraph_format.space_after = Pt(5)
        st['Normal'].paragraph_format.line_spacing = 1.4
        for name, size in (('Title', 22), ('Heading 1', 15), ('Heading 2', 12), ('Heading 3', 10.5)):
            style_fonts(st[name], LATIN, ZH, size=size, bold=True, color='1F3B57', lang_ea='zh-CN')
            st[name].paragraph_format.space_before = Pt(12 if name != 'Heading 3' else 8)
            st[name].paragraph_format.space_after = Pt(5)
            st[name].paragraph_format.keep_with_next = True
        # Title style has a bottom border in the default template; keep it simple.
        footer = self.doc.sections[0].footer.paragraphs[0]
        footer.text = ''
        r = footer.add_run('XC-400 安装与维护手册 · 合成样例 Synthetic sample　　　　第 ')
        r.font.size = Pt(8)
        add_field(footer, 'PAGE')
        r2 = footer.add_run(' 页')
        r2.font.size = Pt(8)
        footer.alignment = WD_ALIGN_PARAGRAPH.CENTER

    def runs(self, p, text, size=None, bold=False):
        """Text with {Japanese} segments (IPAGothic, ja-JP) and **bold** segments."""
        import re
        for part in re.split(r'(\{[^}]*\}|\*\*[^*]*\*\*)', text):
            if not part:
                continue
            if part.startswith('{'):
                r = p.add_run(part[1:-1])
                set_run_fonts(r._element, LATIN, JA, 'ja-JP')
            elif part.startswith('**'):
                r = p.add_run(part[2:-2])
                r.bold = True
            else:
                r = p.add_run(part)
            if size:
                r.font.size = Pt(size)
            if bold:
                r.bold = True
        return p

    def p(self, text, **kw):
        return self.runs(self.doc.add_paragraph(), text, **kw)

    def h(self, text, level):
        return self.runs(self.doc.add_paragraph(style=f'Heading {level}'), text)

    def table(self, header, rows, widths, ja_cols=(), size=8.5, header_fill='DCE6F0'):
        t = self.doc.add_table(rows=1, cols=len(header))
        t.style = 'Table Grid'
        hdr = t.rows[0]
        repeat_header(hdr)
        for i, txt in enumerate(header):
            c = hdr.cells[i]
            c.paragraphs[0].paragraph_format.space_before = Pt(2)
            c.paragraphs[0].paragraph_format.space_after = Pt(2)
            self.runs(c.paragraphs[0], txt, size=size, bold=True)
            shade(c, header_fill)
        for row in rows:
            cells = t.add_row()
            cant_split(cells)
            for i, txt in enumerate(row):
                para = cells.cells[i].paragraphs[0]
                para.paragraph_format.space_before = Pt(1.5)
                para.paragraph_format.space_after = Pt(1.5)
                para.paragraph_format.line_spacing = 1.15
                self.runs(para, '{' + txt + '}' if i in ja_cols and txt not in ('', '–') else txt, size=size)
        total = sum(widths)
        set_col_widths(t, [w * min(1.0, 16.0 / total) for w in widths])
        self.doc.add_paragraph().paragraph_format.space_after = Pt(2)
        return t


