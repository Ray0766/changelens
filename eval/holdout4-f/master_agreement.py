def build(v, out):
    doc = Document()
    a4(doc, top=2.5, bottom=2.4, left=2.5, right=2.5)
    st = doc.styles
    style_fonts(st['Normal'], SERIF, None, size=10.5)
    st['Normal'].paragraph_format.space_after = Pt(5)
    st['Normal'].paragraph_format.line_spacing = 1.2

    footer = doc.sections[0].footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = footer.add_run('Master Services Agreement · Synthetic sample · Page ')
    r.font.size = Pt(8)
    add_field(footer, 'PAGE')
    r = footer.add_run(' of ')
    r.font.size = Pt(8)
    add_field(footer, 'NUMPAGES')

    def para(text, left=0.0, hang=0.0, bold=False, size=None, align=None, space_after=None, keep=False, font=None):
        p = doc.add_paragraph()
        pf = p.paragraph_format
        if left:
            pf.left_indent = Cm(left)
        if hang:
            pf.first_line_indent = Cm(-hang)
            pf.tab_stops.add_tab_stop(Cm(left))
        if align is not None:
            p.alignment = align
        if space_after is not None:
            pf.space_after = Pt(space_after)
        if keep:
            pf.keep_with_next = True
        for part in re.split(r'(\*\*[^*]*\*\*)', text):
            if not part:
                continue
            run = p.add_run(part[2:-2] if part.startswith('**') else part)
            run.bold = bold or part.startswith('**')
            if size:
                run.font.size = Pt(size)
            if font:
                run.font.name = font
        return p

    # Cover
    for _ in range(4):
        doc.add_paragraph()
    para('MASTER SERVICES AGREEMENT', bold=True, size=20, align=WD_ALIGN_PARAGRAPH.CENTER, font=SANS)
    para('for managed IT services', size=13, align=WD_ALIGN_PARAGRAPH.CENTER, font=SANS)
    doc.add_paragraph()
    para('between', align=WD_ALIGN_PARAGRAPH.CENTER)
    para(f'{CUSTOMER}', bold=True, align=WD_ALIGN_PARAGRAPH.CENTER)
    para('(the “Customer”)', align=WD_ALIGN_PARAGRAPH.CENTER)
    para('and', align=WD_ALIGN_PARAGRAPH.CENTER)
    para(f'{SUPPLIER}', bold=True, align=WD_ALIGN_PARAGRAPH.CENTER)
    para('(the “Supplier”)', align=WD_ALIGN_PARAGRAPH.CENTER)
    for _ in range(6):
        doc.add_paragraph()
    para('Synthetic sample. Both parties are fictional companies and this agreement was written for software testing. It is not legal advice and must not be used as a template.', size=9, align=WD_ALIGN_PARAGRAPH.CENTER)
    page_break(doc)

