def compile_case(case, outdir):
    src = os.path.join(H, case["src"])
    if "build" in case:
        case["build"](src)
    for v in ("before", "after"):
        _, warnings = typst.compile_with_warnings(
            src, output=os.path.join(outdir, f"{v}.pdf"), root=H, font_paths=FONT_PATHS,
            ignore_system_fonts=True, sys_inputs={"v": v}, timestamp=TIMESTAMP)
        for w in warnings:
            print(f"  warning ({case['id']}, {v}): {w}", file=sys.stderr)


def graphic_rects(case, outdir):
    """Fill rects of graphic items from the drawings in the produced PDFs (PyMuPDF)."""
    import pymupdf
    if case["id"] == "holdout5-h-rapport-annuel":
        # the December bar (last bar of colour #3b6e8f); rect spans the taller of the two bars
        res = {}
        for v in ("before", "after"):
            doc = pymupdf.open(os.path.join(outdir, f"{v}.pdf"))
            page = doc[1]
            bars = [d["rect"] for d in page.get_drawings() if d.get("fill") and abs(d["fill"][0] - 0x3b / 255) < 0.01 and abs(d["fill"][2] - 0x8f / 255) < 0.01]
            bars.sort(key=lambda r: r.x0)
            res[v] = bars[-1]
        top = min(res["before"].y0, res["after"].y0)
        for v, key in (("before", "oldRect"), ("after", "newRect")):
            r = res[v]
            h_extra = r.y0 - top  # extend each side's rect to cover the other version's bar height
            case_rect = [round(r.x0 - 2, 1), round(r.y0 - h_extra - 2, 1), round(r.width + 4, 1), round(r.height + h_extra + 4, 1)]
            for it in case["truth"]:
                if it["type"] == "graphic":
                    it[key] = case_rect
    if case["id"] == "holdout5-h-pruefbericht":
        for v, key in (("before", "oldRect"), ("after", "newRect")):
            doc = pymupdf.open(os.path.join(outdir, f"{v}.pdf"))
            page = doc[1]
            bars = [d["rect"] for d in page.get_drawings() if d.get("fill") and d["type"] == "f" and d["rect"].height > 10 and d["rect"].width > 60]
            bars.sort(key=lambda r: r.y0)
            r = bars[1]  # M6, M7, M8 from top: M7 is the middle one
            for it in case["truth"]:
                if it["type"] == "graphic":
                    it[key] = [round(r.x0 - 2, 1), round(r.y0 - 2, 1), round(r.width + 4, 1), round(r.height + 4, 1)]


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(2)
    root = os.path.abspath(sys.argv[1])
    for case in CASES:
        outdir = os.path.join(root, case["id"])
        os.makedirs(outdir, exist_ok=True)
        compile_case(case, outdir)
        graphic_rects(case, outdir)
        truth = {
            "description": case["description"] + " Producer: " + case.get("producer", PRODUCER) + ". Synthetic sample: all parties, places and figures are fictitious.",
            "synthetic": True,
            "set": "held-out-5",
            "blind": True,
            "truth": case["truth"],
        }
        with open(os.path.join(outdir, "truth.json"), "w", encoding="utf-8") as f:
            json.dump(truth, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print(f"{case['id']}: {len(case['truth'])} truth items -> {outdir}")


if __name__ == "__main__":
    main()
